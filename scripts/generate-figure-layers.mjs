import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { emitGenerated } from "./generated-file.mjs";
import { decodePng } from "./png.mjs";

/**
 * Indexes the player figure's layers for `PlayerFigure`: the body
 * (`assets/layers/body.png`, made by `npm run layer:base`) and each gear layer
 * in `assets/layers/<slot>/<appearance>.png` (made by `npm run layer:add`).
 *
 * Why: Metro only bundles images named in a literal `require()`, so a layer
 * picked at runtime by an item's appearance needs one `require` per file.
 *
 * Also records the canvas size and the body's bounding box (its opaque
 * pixels), so the figure can be sized by the body while weapons reach past it.
 *
 * Runs on its own: `npm start` runs it first and again whenever the layers
 * change (scripts/dev.mjs), and `layer:add` / `layer:base` run it. `npm run
 * figure-layers` does it by hand. `--check` (part of `npm run check`) fails
 * when the index is out of date, without writing it.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const layersDir = join(root, "src/features/character/assets/layers");
const outFile = join(root, "src/features/character/figureLayers.generated.ts");

/** Layer folders, as `layer:add` names them. */
const SLOTS = ["legs", "chest", "head", "main-hand", "off-hand"];
const NAME_PATTERN = /^[a-z0-9]+([.-][a-z0-9]+)*$/;

const bodyFile = join(layersDir, "body.png");
let header = "export const FIGURE_BODY: ImageSourcePropType | null = null;\nexport const FIGURE_CANVAS = { width: 1, height: 1 } as const;\nexport const FIGURE_BODY_BOX = { x: 0, y: 0, width: 1, height: 1 } as const;";
if (existsSync(bodyFile)) {
    const body = decodePng(readFileSync(bodyFile), bodyFile);
    const box = opaqueBox(body);
    header = [
        `/** The base character, every layer's canvas. */`,
        `export const FIGURE_BODY: ImageSourcePropType | null = require("./assets/layers/body.png");`,
        `/** Every layer's size, in pixels. */`,
        `export const FIGURE_CANVAS = { width: ${body.width}, height: ${body.height} } as const;`,
        `/** Where the body's opaque pixels are on the canvas: the figure is sized by this. */`,
        `export const FIGURE_BODY_BOX = { x: ${box.x}, y: ${box.y}, width: ${box.width}, height: ${box.height} } as const;`,
    ].join("\n");
}

const slotLines = SLOTS.map((slot) => {
    const dir = join(layersDir, slot);
    const files = existsSync(dir) && statSync(dir).isDirectory() ? readdirSync(dir).filter((f) => f.endsWith(".png")).sort() : [];
    const entries = files.map((file) => {
        const name = basename(file, ".png");
        if (!NAME_PATTERN.test(name)) throw new Error(`layers/${slot}/${file}: name layers in kebab-case, like bronze-dagger.png.`);
        return `        ${JSON.stringify(name)}: require(${JSON.stringify(`./assets/layers/${slot}/${file}`)}),`;
    });
    return `    ${JSON.stringify(slot)}: {${entries.length ? `\n${entries.join("\n")}\n    ` : ""}},`;
});

const output = `// Generated by scripts/generate-figure-layers.mjs — do not edit. Run \`npm run figure-layers\`.

import type { ImageSourcePropType } from "react-native";

${header}

/** Gear layers, by layer slot, then appearance (the item's id unless it shares another's look). */
export const FIGURE_LAYERS: Record<FigureLayerSlot, Record<string, ImageSourcePropType>> = {
${slotLines.join("\n")}
};

export type FigureLayerSlot = ${SLOTS.map((s) => JSON.stringify(s)).join(" | ")};
`;

emitGenerated(outFile, output, { root, script: "figure-layers" });

/** Bounding box of pixels with any opacity. */
function opaqueBox({ width, height, pixels }) {
    let x0 = width, y0 = height, x1 = -1, y1 = -1;
    for (let y = 0; y < height; y++) {
        for (let x = 0; x < width; x++) {
            if (pixels[(y * width + x) * 4 + 3] <= 8) continue;
            if (x < x0) x0 = x;
            if (x > x1) x1 = x;
            if (y < y0) y0 = y;
            if (y > y1) y1 = y;
        }
    }
    return x1 < 0 ? { x: 0, y: 0, width, height } : { x: x0, y: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 };
}

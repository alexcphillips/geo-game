import { readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Indexes the pet icons in `src/features/pets/assets/*.png` by name.
 *
 * Why: Metro only bundles images named in a literal `require()`, so a pet the
 * server names by id can't be looked up at runtime from a path. This writes
 * one `require` per file into a map keyed by the file's name (`ember-fox.png`
 * → `"ember-fox"`), which is the id pet data will use.
 *
 * Unlike map sprites, these are drawn by the app's own screens, not the map's
 * WebView, so they stay ordinary bundled assets: no cropping or embedding.
 *
 * Run with `npm run pet-icons` after adding, renaming or removing an icon.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assetsDir = join(root, "src/features/pets/assets");
const outFile = join(root, "src/features/pets/petIcons.generated.ts");

/** Lowercase words joined by hyphens, matching content ids. */
const NAME_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const names = readdirSync(assetsDir)
    .filter((file) => file.endsWith(".png"))
    .sort()
    .map((file) => {
        const name = basename(file, ".png");
        if (!NAME_PATTERN.test(name)) {
            throw new Error(`${file}: name pet icons in kebab-case, like ember-fox.png.`);
        }
        return name;
    });

const entries = names.map((name) => `    ${JSON.stringify(name)}: require(${JSON.stringify(`./assets/${name}.png`)}),`);

writeFileSync(
    outFile,
    `// Generated by scripts/generate-pet-icons.mjs — do not edit. Run \`npm run pet-icons\`.

import type { ImageSourcePropType } from "react-native";

/** Pet icons, by name: each \`assets/<name>.png\`. */
export const PET_ICONS = {${entries.length ? `\n${entries.join("\n")}\n` : ""}} as const satisfies Record<string, ImageSourcePropType>;

export type PetIconName = keyof typeof PET_ICONS;
`,
);

console.log(`${names.length} pet icon${names.length === 1 ? "" : "s"}: ${names.join(", ") || "none yet"}`);

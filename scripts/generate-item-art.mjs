import { readdirSync, statSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CHECK, emitGenerated } from "./generated-file.mjs";

/**
 * Indexes the item art in `src/features/items/art/<folder>/*.png` by name.
 *
 * Why: Metro only bundles images named in a literal `require()`, so an item
 * the server names by id can't be looked up at runtime from a path. This writes
 * one `require` per file into a map keyed by the file's name
 * (`weapons/bronze-dagger.png` → `"bronze-dagger"`).
 *
 * A file is named for the item's id, or for a pet its content `image`. The
 * folders (weapons, armor, pets…) are only for keeping the art tidy: lookup
 * ignores them, so two files with the same name in different folders fail the
 * script rather than one silently winning.
 *
 * Unlike map sprites, these are drawn by the app's own screens, not the map's
 * WebView, so they stay ordinary bundled assets: no cropping or embedding.
 *
 * Runs on its own: `npm start` (and tunnel, android, ios) runs it first and
 * again whenever the art folders change (scripts/dev.mjs). `npm run item-art`
 * does it by hand. `--check` (part of `npm run check`) fails when the index is
 * out of date, without writing it.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artDir = join(root, "src/features/items/art");
const outFile = join(root, "src/features/items/itemArt.generated.ts");

/** Lowercase words joined by hyphens or dots, matching content ids. */
const NAME_PATTERN = /^[a-z0-9]+([.-][a-z0-9]+)*$/;

const folders = readdirSync(artDir)
    .filter((entry) => statSync(join(artDir, entry)).isDirectory())
    .sort();

/** Name → path relative to the generated file. */
const art = new Map();
for (const folder of folders) {
    for (const file of readdirSync(join(artDir, folder)).sort()) {
        if (!file.endsWith(".png")) continue;
        const name = basename(file, ".png");
        if (!NAME_PATTERN.test(name)) {
            throw new Error(`${folder}/${file}: name item art for its id in kebab-case, like bronze-dagger.png.`);
        }
        if (art.has(name)) {
            throw new Error(`${folder}/${file}: ${art.get(name)} already has the name "${name}".`);
        }
        art.set(name, `./art/${folder}/${file}`);
    }
}

const names = [...art.keys()].sort();
const entries = names.map((name) => `    ${JSON.stringify(name)}: require(${JSON.stringify(art.get(name))}),`);

const output = `// Generated by scripts/generate-item-art.mjs — do not edit. Run \`npm run item-art\`.

import type { ImageSourcePropType } from "react-native";

/** Item art, by name: each \`art/<folder>/<name>.png\`. */
export const ITEM_ART = {${entries.length ? `\n${entries.join("\n")}\n` : ""}} as const satisfies Record<string, ImageSourcePropType>;
`;

const changed = emitGenerated(outFile, output, { root, script: "item-art" });
if (changed && !CHECK) {
    console.log(`${names.length} item art file${names.length === 1 ? "" : "s"}: ${names.join(", ") || "none yet"}`);
}
